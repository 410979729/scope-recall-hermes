@pytest.mark.parametrize("value", [*NEGATED_STATES["zh"], *NEGATED_STATES["en"]])
def test_a_description_or_polar_answer_remains_a_value_without_target_evidence(value):
    for kind in ("fact", "preference"):
        payload = {"kind": kind, "value_text": value}
        assert not is_denial(payload)
        assert not is_denial(payload, (payload,))
        assert not negates(payload, payload)


@pytest.mark.parametrize("value", [*NAMED_DENIALS["zh"], *NAMED_DENIALS["en"]])
def test_a_name_identifier_or_targeted_action_is_positive_denial_evidence(value):
    for kind in ("fact", "preference"):
        assert is_denial({"kind": kind, "value_text": value})
    assert not is_denial({"kind": "constraint", "value_text": value})


@pytest.mark.parametrize("value,held", [*HELD_DENIALS["zh"], *HELD_DENIALS["en"]])
def test_slot_history_identifies_a_target_in_any_case(value, held):
    payload = {"kind": "fact", "value_text": value}
    assert not is_denial(payload)
    assert is_denial(payload, ({"value_text": held},))
    assert negates(payload, {"value_text": held})


def test_each_language_has_forty_values_on_each_side():
    assert all(len(values) >= 40 for table in (NEGATED_STATES, NAMED_DENIALS) for values in table.values())


NEGATIVE_STATE_TRANSITIONS = (
    ("not online", "online"),
    ("not Configured", "configured"),
    ("not fast", "fast"),
    ("not available", "available"),
    ("not stable", "stable"),
    ("is not reachable", "reachable"),
    ("不在线", "在线"),
    ("不是默认的", "默认的"),
)


@pytest.mark.parametrize("value,held", NEGATIVE_STATE_TRANSITIONS)
def test_a_state_description_is_not_a_denial_even_when_slot_holds_the_positive_state(value, held):
    payload = {"kind": "fact", "value_text": value}
    held_payload = {"value_text": held}
    assert not is_denial(payload)
    assert not is_denial(payload, (held_payload,))
    assert not negates(payload, held_payload)
